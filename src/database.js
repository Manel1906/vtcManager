
require("dotenv").config();

const { Pool } = require("pg");

// ========================================
// CONNEXION POSTGRESQL
// ========================================

const db = new Pool({
  host: process.env.DB_HOST || "localhost",
  port: Number(process.env.DB_PORT) || 5432,
  database: process.env.DB_NAME || "vtc",
  user: process.env.DB_USER || "postgres",
  password: process.env.DB_PASSWORD,
  max: 10,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 5000
});

// Gestion des erreurs de connexion
db.on("error", (err) => {
  console.error("Erreur PostgreSQL :", err);
});

// ========================================
// INITIALISATION DE LA BASE
// ========================================

async function initDatabase() {
  const client = await db.connect();

  try {
    await client.query("BEGIN");

    // ========================================
    // UTILISATEURS
    // ========================================

    await client.query(`
      CREATE TABLE IF NOT EXISTS users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nom TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        role TEXT NOT NULL DEFAULT 'user',
        actif INTEGER NOT NULL DEFAULT 1,
        photo TEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      );
    `);

    // ========================================
    // ENTREPRISES
    // ========================================

    await client.query(`
      CREATE TABLE IF NOT EXISTS entreprise (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL UNIQUE,
        nom TEXT,
        siret TEXT,
        revtc TEXT,
        telephone TEXT,
        email TEXT,
        adresse TEXT,
        chauffeur TEXT,

        FOREIGN KEY (user_id)
          REFERENCES users(id)
          ON DELETE CASCADE
      );
    `);

    // ========================================
    // CLIENTS
    // ========================================

    await client.query(`
      CREATE TABLE IF NOT EXISTS clients (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL,
        nom TEXT NOT NULL,
        telephone TEXT,
        email TEXT,
        adresse TEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

        FOREIGN KEY (user_id)
          REFERENCES users(id)
          ON DELETE CASCADE
      );
    `);

    // ========================================
    // RESERVATIONS
    // ========================================

    await client.query(`
      CREATE TABLE IF NOT EXISTS reservations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL,
        client_id INTEGER,

        date_reservation TEXT,
        heure_reservation TEXT,
        date_prise_en_charge TEXT,
        heure_prise_en_charge TEXT,

        depart TEXT,
        destination TEXT,
        passager TEXT,

        tarif_km DOUBLE PRECISION DEFAULT 0,
        distance_km DOUBLE PRECISION DEFAULT 0,
        prix_ttc DOUBLE PRECISION DEFAULT 0,

        mode_reglement TEXT,
        pdf TEXT,

        entreprise_nom TEXT,
        entreprise_siret TEXT,
        entreprise_revtc TEXT,
        entreprise_telephone TEXT,
        entreprise_email TEXT,
        entreprise_adresse TEXT,
        entreprise_chauffeur TEXT,

        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

        FOREIGN KEY (user_id)
          REFERENCES users(id)
          ON DELETE CASCADE,

        FOREIGN KEY (client_id)
          REFERENCES clients(id)
          ON DELETE SET NULL
      );
    `);

    // ========================================
    // INDEX
    // ========================================

    await client.query(`
      CREATE INDEX IF NOT EXISTS idx_entreprise_user_id
        ON entreprise(user_id);

      CREATE INDEX IF NOT EXISTS idx_clients_user_id
        ON clients(user_id);

      CREATE INDEX IF NOT EXISTS idx_clients_user_email
        ON clients(user_id, email);

      CREATE INDEX IF NOT EXISTS idx_reservations_user_id
        ON reservations(user_id);

      CREATE INDEX IF NOT EXISTS idx_reservations_client_id
        ON reservations(client_id);
    `);

    await client.query("COMMIT");

    console.log("✓ Base PostgreSQL initialisée avec succès");

  } catch (error) {
    await client.query("ROLLBACK");
    console.error("Erreur initialisation PostgreSQL :", error);
    throw error;

  } finally {
    client.release();
  }
}

// ========================================
// EXPORTS
// ========================================

module.exports = db;
module.exports.initDatabase = initDatabase;
